export function loadGroupsFromStorage(): PhotoGroup[] {
  if (typeof window === "undefined") {
    return [];
  }

  try {
    const rawValue = window.localStorage.getItem(PHOTO_STORAGE_KEY);
    if (!rawValue) {
      return [];
    }
    return JSON.parse(rawValue) as PhotoGroup[];
  } catch {
    return [];
  }
}

export function saveGroupsToStorage(groups: PhotoGroup[]): void {
  if (typeof window === "undefined") {
    return;
  }

  window.localStorage.setItem(PHOTO_STORAGE_KEY, JSON.stringify(groups));
}

export function countCityPhotos(groups: PhotoGroup[]): Record<string, number> {
  return groups.reduce<Record<string, number>>((counts, group) => {
    counts[group.city] = (counts[group.city] ?? 0) + group.photos.length;
    return counts;
  }, {});
}

